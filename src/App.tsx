import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { BrowserRouter, Route, Routes } from "react-router-dom";
import { Toaster as Sonner } from "@/components/ui/sonner";
import { Toaster } from "@/components/ui/toaster";
import { TooltipProvider } from "@/components/ui/tooltip";
import Index from "./pages/Index.tsx";
import OrderDetail from "./pages/OrderDetail.tsx";
import FamilyDetail from "./pages/FamilyDetail.tsx";
import SpeciesDetail from "./pages/SpeciesDetail.tsx";
import NotFound from "./pages/NotFound.tsx";

const queryClient = new QueryClient();

const App = () => (
  <QueryClientProvider client={queryClient}>
    <TooltipProvider>
      <Toaster />
      <Sonner />
      <BrowserRouter>
        <Routes>
          <Route path="/" element={<Index />} />
          <Route path="/order/:orderId" element={<OrderDetail />} />
          <Route path="/order/:orderId/family/:familyId" element={<FamilyDetail />} />
          <Route path="/order/:orderId/family/:familyId/species/:speciesId" element={<SpeciesDetail />} />
          <Route path="*" element={<NotFound />} />
        </Routes>
      </BrowserRouter>
    </TooltipProvider>
  </QueryClientProvider>
);

export default App;
